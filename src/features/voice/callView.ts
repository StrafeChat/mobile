/**
 * Which room the call screen shows, and getting to and from it.
 *
 * The call screen (route /call, src/app/(main)/call.tsx) shows one room's stage: the room
 * you are connected to, or - before joining - the room you opened (a voice room's "Join"
 * page, a PM's "Start call"). It follows the session while it shows the session's room, so
 * a moderator moving you, or joining from the screen itself, keeps it on the call you are
 * in. Kept outside React so joinVoiceFromUi, the dock and the incoming-call overlay can
 * point it at a room before it mounts.
 */
import { router } from 'expo-router';
import { createExternalStore } from '@/ui';

export interface CallViewTarget {
  roomId: string;
  spaceId?: string | null;
}

export interface CallViewState {
  /** The room on screen; null shows the session's room. */
  roomId: string | null;
  spaceId: string | null;
  /** Call screens mounted (two only briefly: one closing while another opens). */
  mounted: number;
  /** A close is under way: further closes are no-ops, an open pushes a fresh screen. */
  closing: boolean;
}

export const callViewStore = createExternalStore<CallViewState>({ roomId: null, spaceId: null, mounted: 0, closing: false });

/** The room the call screen is showing, or null for "the session's room". */
export function setCallViewTarget(target: CallViewTarget | null): void {
  callViewStore.set((s) => ({ ...s, roomId: target?.roomId ?? null, spaceId: target?.spaceId ?? null }));
}

/** The call screen calls this on mount (true) and unmount (false). */
export function setCallScreenMounted(mounted: boolean): void {
  callViewStore.set((s) => {
    if (mounted) return { ...s, mounted: s.mounted + 1, closing: false };
    const left = Math.max(0, s.mounted - 1);
    // The last one gone: the next open starts from the session's call again.
    return left === 0 ? { roomId: null, spaceId: null, mounted: 0, closing: false } : { ...s, mounted: left };
  });
}

/** Whether a call screen is on screen and staying there. */
export function callScreenShowing(): boolean {
  const s = callViewStore.get();
  return s.mounted > 0 && !s.closing;
}

/**
 * Show the call screen for `target` (the current call when omitted). Already on screen: it
 * just switches to that room instead of stacking a second copy.
 */
export function openCallScreen(target?: CallViewTarget): void {
  setCallViewTarget(target ?? null);
  if (callScreenShowing()) return;
  // Typed routes are generated by `expo start`; /call is ours (src/app/(main)/call.tsx).
  router.push(
    (target
      ? { pathname: '/call', params: { roomId: target.roomId, ...(target.spaceId ? { spaceId: target.spaceId } : {}) } }
      : '/call') as never,
  );
}

/** Leave the call screen (minimise), back to wherever it was opened from. Safe to call twice. */
export function closeCallScreen(): void {
  if (!callScreenShowing()) return;
  callViewStore.set((s) => ({ ...s, closing: true }));
  if (router.canGoBack()) router.back();
  else router.replace('/' as never);
}
