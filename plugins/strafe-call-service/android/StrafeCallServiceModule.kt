package __PACKAGE__.callservice

import android.content.Intent
import androidx.core.content.ContextCompat
import com.facebook.react.bridge.Arguments
import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod
import com.facebook.react.bridge.ReadableMap

/**
 * `NativeModules.StrafeCallService` - start/update/stop for StrafeCallService (see there),
 * and the `StrafeCallServiceEvent` device event that carries its notification's buttons
 * (`{ type: 'action', action: 'mute' | 'hangup' }`) and its end (`{ type: 'stopped' }`)
 * back to JavaScript. Generated by plugins/withStrafeCallService.js.
 */
class StrafeCallServiceModule(private val context: ReactApplicationContext) : ReactContextBaseJavaModule(context) {
  init {
    current = this
  }

  override fun getName(): String = NAME

  override fun invalidate() {
    if (current === this) current = null
    super.invalidate()
  }

  companion object {
    const val NAME = "StrafeCallService"
    const val EVENT = "StrafeCallServiceEvent"

    @Volatile private var current: StrafeCallServiceModule? = null

    private fun emit(type: String, action: String?): Boolean {
      val ctx = current?.context ?: return false
      if (!ctx.hasActiveReactInstance()) return false
      return try {
        val map = Arguments.createMap()
        map.putString("type", type)
        if (action != null) map.putString("action", action)
        ctx.emitDeviceEvent(EVENT, map)
        true
      } catch (e: Exception) {
        false
      }
    }

    /** A notification button was pressed. False when no JavaScript is there to hear it. */
    fun emitAction(action: String): Boolean = emit("action", action)

    /** The service ended (stopped, refused the foreground, or the task was removed). */
    fun emitStopped() {
      emit("stopped", null)
    }
  }

  private fun intentFor(options: ReadableMap): Intent =
    Intent(context, StrafeCallService::class.java).apply {
      fun str(key: String) = if (options.hasKey(key) && !options.isNull(key)) options.getString(key) else null
      fun bool(key: String) = options.hasKey(key) && !options.isNull(key) && options.getBoolean(key)
      putExtra(StrafeCallService.EXTRA_TITLE, str("title"))
      putExtra(StrafeCallService.EXTRA_TEXT, str("text"))
      putExtra(StrafeCallService.EXTRA_CHANNEL_NAME, str("channelName"))
      putExtra(StrafeCallService.EXTRA_CAMERA, bool("camera"))
      putExtra(StrafeCallService.EXTRA_MUTED, bool("muted"))
      putExtra(StrafeCallService.EXTRA_MUTE_LABEL, str("muteLabel"))
      putExtra(StrafeCallService.EXTRA_HANG_UP_LABEL, str("hangUpLabel"))
    }

  @ReactMethod
  fun start(options: ReadableMap, promise: Promise) {
    try {
      ContextCompat.startForegroundService(context, intentFor(options))
      promise.resolve(true)
    } catch (e: Exception) {
      promise.reject("call_service_start_failed", e.message, e)
    }
  }

  /**
   * Change the running notification (mute state, labels) without starting the service
   * again - which Android forbids from the background, where a notification button is
   * pressed. Resolves false when the service is not running.
   */
  @ReactMethod
  fun update(options: ReadableMap, promise: Promise) {
    try {
      promise.resolve(StrafeCallService.update(intentFor(options)))
    } catch (e: Exception) {
      promise.reject("call_service_update_failed", e.message, e)
    }
  }

  @ReactMethod
  fun stop(promise: Promise) {
    try {
      context.stopService(Intent(context, StrafeCallService::class.java))
      promise.resolve(true)
    } catch (e: Exception) {
      promise.reject("call_service_stop_failed", e.message, e)
    }
  }
}
