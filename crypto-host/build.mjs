/**
 * Build the crypto host page: `npm run build:crypto-host`.
 *
 * Emits, into assets/crypto/:
 * - hostPage.js (+ .d.ts): the page's HTML as a string, with the bundled host script inline,
 *   and the SHA-256 of the engine wasm it will accept. The app passes the HTML to the
 *   WebView as `source={{ html, baseUrl: 'https://e2ee.strafe.invalid/' }}`.
 * - matrix_sdk_crypto_wasm_bg.wasm: the engine, shipped as an app asset and posted into the
 *   page as base64 slices at boot (see src/platform/crypto/README.md for why not a URL).
 *
 * The page's CSP allows exactly its own inline script (by hash) and wasm compilation, and no
 * connections at all: the engine has nothing to talk to but the app.
 *
 * Re-run after bumping @matrix-org/matrix-sdk-crypto-wasm or editing crypto-host/src.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const require = createRequire(import.meta.url);
const { locateMatrixSdkCryptoWasm, PKG } = require('./locatePackage.cjs');

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');
const OUT = path.join(ROOT, 'assets', 'crypto');

const pkg = locateMatrixSdkCryptoWasm();
if (!pkg) {
  console.error(`${PKG} is not installed (looked in node_modules and web/node_modules; set MATRIX_SDK_CRYPTO_WASM_DIR to point elsewhere).`);
  process.exit(1);
}

// The facade (src/platform/crypto/matrixSdkCrypto.ts) mirrors this major's API; a different
// major needs the facade and the host reviewed together, not a silent rebuild.
const webRange = JSON.parse(readFileSync(path.join(ROOT, 'web', 'package.json'), 'utf8')).dependencies?.[PKG] ?? '';
const major = (v) => String(v).replace(/^[^\d]*/, '').split('.')[0];
if (webRange && major(webRange) !== major(pkg.version)) {
  console.error(`${PKG} ${pkg.version} does not match the web client's ${webRange}; update the facade before building.`);
  process.exit(1);
}

const wasm = readFileSync(pkg.wasm);
const wasmSha256 = createHash('sha256').update(wasm).digest('hex');

const bindingsAlias = {
  name: 'matrix-sdk-crypto-wasm-bindings',
  setup(build) {
    build.onResolve({ filter: /^matrix-sdk-crypto-wasm-bindings$/ }, () => ({ path: pkg.bindingsEsm }));
  },
};

const result = await esbuild.build({
  entryPoints: [path.join(HERE, 'src', 'main.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  // BigInt and async/await natively: WebViews from the last several years (Android System
  // WebView updates through the Play Store; iOS 15+ WKWebView).
  target: ['es2020', 'chrome89', 'safari15'],
  minify: true,
  // Class names cross the bridge: an engine throwable that is not an Error (the decrypt
  // failure, MegolmDecryptionError) is reported by its constructor's name (protocol.ts
  // toWireError), which plain minification renames to two letters.
  keepNames: true,
  legalComments: 'none',
  define: { __WASM_SHA256__: JSON.stringify(wasmSha256) },
  plugins: [bindingsAlias],
  logLevel: 'warning',
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const scriptHash = createHash('sha256').update(script).digest('base64');

const csp = [
  "default-src 'none'",
  `script-src 'sha256-${scriptHash}' 'wasm-unsafe-eval'`,
  "connect-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
].join('; ');

const html =
  '<!doctype html><html><head><meta charset="utf-8">' +
  `<meta http-equiv="Content-Security-Policy" content="${csp}">` +
  '<title>Strafe crypto host</title></head><body>' +
  `<script>${script}</script>` +
  '</body></html>';

mkdirSync(OUT, { recursive: true });

const generated = `// Generated by crypto-host/build.mjs from ${PKG} ${pkg.version} - do not edit.\n`;
writeFileSync(
  path.join(OUT, 'hostPage.js'),
  generated +
    `export const HOST_HTML = ${JSON.stringify(html)};\n` +
    `export const WASM_SHA256 = ${JSON.stringify(wasmSha256)};\n` +
    `export const WASM_SIZE = ${wasm.length};\n` +
    `export const ENGINE_PACKAGE_VERSION = ${JSON.stringify(pkg.version)};\n`,
);
writeFileSync(
  path.join(OUT, 'hostPage.d.ts'),
  generated +
    '/** The crypto host page, with its script inline. */\nexport declare const HOST_HTML: string;\n' +
    '/** SHA-256 (hex) of the engine wasm the page accepts. */\nexport declare const WASM_SHA256: string;\n' +
    'export declare const WASM_SIZE: number;\n' +
    'export declare const ENGINE_PACKAGE_VERSION: string;\n',
);

const wasmOut = path.join(OUT, 'matrix_sdk_crypto_wasm_bg.wasm');
if (!existsSync(wasmOut) || createHash('sha256').update(readFileSync(wasmOut)).digest('hex') !== wasmSha256) {
  writeFileSync(wasmOut, wasm);
}

console.log(
  `crypto host: ${PKG} ${pkg.version}, page ${(html.length / 1024).toFixed(0)} KiB, ` +
    `wasm ${(wasm.length / 1048576).toFixed(1)} MiB (sha256 ${wasmSha256.slice(0, 12)}...)`,
);
